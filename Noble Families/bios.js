function personBio(name) {
  const fact = typeof PERSON_FACTS !== "undefined" ? PERSON_FACTS[name] : null;
  const wikiOnly = typeof PERSON_BIOS_AUTO !== "undefined" ? PERSON_BIOS_AUTO[name] : null;
  const hand = PERSON_BIOS[name];
  if (!hand && !fact && !wikiOnly) return null;
  const out = Object.assign({}, wikiOnly || {}, fact || {}, hand || {});
  const bad = /打开下方|有公开肖像才会|点关系栏/;
  if (out.did && bad.test(out.did)) delete out.did;
  if (out.family && /^属于/.test(out.family) && out.family.length < 20) delete out.family;
  return out;
}
